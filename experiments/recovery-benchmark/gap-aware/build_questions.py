def main() -> None:
    assigned = assign_panels(ROWS)
    path = ROOT / "questions.jsonl"
    path.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in assigned))
    counts: dict[str, dict[str, int]] = {}
    for row in assigned:
        bucket = counts.setdefault(row["stratum"], {"development": 0, "holdout": 0})
        bucket[row["panel"]] += 1
    split = {
        "seed": "20261007-gap",
        "modulus": 3,
        "holdout_residue": 0,
        "status": "sealed_until_candidate_selection",
        "outcomes_inspected": False,
        "phase8a_holdout": "phase8a_holdout_consumed",
        "n": len(assigned),
        "n_development": sum(row["panel"] == "development" for row in assigned),
        "n_holdout": sum(row["panel"] == "holdout" for row in assigned),
        "by_stratum": counts,
        "question_ids": {row["question_id"]: row["panel"] for row in assigned},
    }
    (ROOT / "split.json").write_text(json.dumps(split, indent=2) + "\n")
    print(json.dumps({"n": split["n"], "development": split["n_development"], "holdout": split["n_holdout"], "by_stratum": counts}, indent=2))


if __name__ == "__main__":
    main()
